"""The models and the migrations describe the same schema.

Runs ``alembic check`` against the test database, which must be migrated to head.
A difference here is what ``alembic revision --autogenerate`` would write into the
next migration, and it is often destructive: a table or index that a migration
created but no model declares comes out as a drop.
"""

from __future__ import annotations

from pathlib import Path

import pytest
from alembic import command
from alembic.config import Config
from alembic.util import AutogenerateDiffsDetected

MIGRATIONS = Path(__file__).resolve().parents[1] / "migrations"


def test_models_match_the_migrated_schema(_engine, monkeypatch):
    # No alembic.ini: env.py would pass it to logging.config.fileConfig, which
    # disables every logger that already exists, the app's included.
    config = Config()
    config.set_main_option("script_location", str(MIGRATIONS))
    # env.py loads backend/.env for the CLI; here that would put a developer's
    # real API keys in the environment of the tests that run after this one.
    monkeypatch.setattr("dotenv.load_dotenv", lambda *args, **kwargs: False)

    try:
        command.check(config)
    except AutogenerateDiffsDetected as exc:
        diffs = str(exc)
    else:
        return
    pytest.fail(
        "The models and the migrated database disagree; the next autogenerated "
        "migration would contain these operations. Declare on the models what the "
        f"migrations created, or add a migration.\n{diffs}",
        pytrace=False,
    )
